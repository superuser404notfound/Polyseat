package seat

import (
	"strings"
	"testing"
)

// The image's list, as the Arch image Incus starts a seat from ships it.
const imageMirrorlist = "##\n## Arch Linux repository mirrorlist\n##\n\n" +
	"Server = http://mirrors.kernel.org/archlinux/$repo/os/$arch\n"

// A CachyOS host's list, the head of it, comments and all.
const cachyHostMirrorlist = "## Generated by reflector\n" +
	"Server = https://archlinux.cachyos.org/repo/$repo/os/$arch\n" +
	"#Server = https://commented.out/$repo/os/$arch\n" +
	"Server = https://ftp.energotel.sk/pub/linux/arch/$repo/os/$arch\n" +
	"Server = https://arch.midov.pl/arch/$repo/os/$arch\n" +
	"Server = https://mirror.lu.stratonexus.net/archlinux/$repo/os/$arch\n" +
	"Server = https://al.arch.niranjan.co/$repo/os/$arch\n" +
	"Server = https://sixth.example/$repo/os/$arch\n"

func TestTheImagesMirrorlistGetsNearerMirrors(t *testing.T) {
	list, ok := betterMirrorlist(imageMirrorlist, cachyHostMirrorlist)
	if !ok {
		t.Fatal("the image's one mirror was kept")
	}

	want := []string{
		geoMirror,
		"https://archlinux.cachyos.org/repo/$repo/os/$arch",
		"https://ftp.energotel.sk/pub/linux/arch/$repo/os/$arch",
		"https://arch.midov.pl/arch/$repo/os/$arch",
		"https://mirror.lu.stratonexus.net/archlinux/$repo/os/$arch",
		"http://mirrors.kernel.org/archlinux/$repo/os/$arch",
	}

	if got := mirrorServers(list); strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("the list is\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

// A Debian or Fedora host has no list, and the geo mirror alone is still
// better than Dallas.
func TestAHostWithoutAMirrorlistStillHelps(t *testing.T) {
	list, ok := betterMirrorlist(imageMirrorlist, "")
	if !ok {
		t.Fatal("kept the image's list")
	}

	if got := mirrorServers(list); len(got) != 2 || got[0] != geoMirror {
		t.Errorf("the list is %v", got)
	}

	// An empty or missing list in the seat gets one too.
	if list, ok := betterMirrorlist("", ""); !ok || len(mirrorServers(list)) != 1 {
		t.Errorf("an empty list became %q", list)
	}
}

// Two servers or more is somebody's choice, or one written here, and is left
// alone, which is also what makes this safe to run on every provisioning.
func TestAChosenMirrorlistIsKept(t *testing.T) {
	if _, ok := betterMirrorlist(cachyHostMirrorlist, ""); ok {
		t.Error("a list of six servers was replaced")
	}

	list, _ := betterMirrorlist(imageMirrorlist, cachyHostMirrorlist)
	if _, ok := betterMirrorlist(list, cachyHostMirrorlist); ok {
		t.Error("the list written here was replaced the next time")
	}
}

// What is copied from the host goes into a file pacman reads as root, so only
// a plain address is taken: no second directive on the line, nothing that is
// not http.
func TestOnlyPlainServerLinesAreTakenFromTheHost(t *testing.T) {
	host := "Server = file:///etc/$repo\n" +
		"Server = https://ok.example/$repo/os/$arch\n" +
		"Server = https://bad.example/$repo/os/$arch\nInclude = /etc/x\n" +
		"Server = https://space.example/$repo os/$arch\n" +
		"Server = https://norepo.example/os\n"

	got := mirrorServers(host)
	if len(got) != 2 || got[0] != "https://ok.example/$repo/os/$arch" || got[1] != "https://bad.example/$repo/os/$arch" {
		t.Errorf("took %v", got)
	}

	list, _ := betterMirrorlist(imageMirrorlist, host)
	if strings.Contains(list, "Include") || strings.Contains(list, "file:") {
		t.Errorf("the list carries more than servers:\n%s", list)
	}
}
